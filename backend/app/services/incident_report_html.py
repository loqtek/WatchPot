def render_html(report: IncidentReport) -> str:
    scope = report.scope
    body = [
        "<header>",
        '<p class="brand">watchPot</p>',
        f"<h1>{_esc(scope.title)}</h1>",
        '<p class="lede">Incident report for honeypot activity. All timestamps are UTC.</p>',
        _meta_table(
            [
                ("Generated", f"{format_ts(scope.generated_at)} by {scope.generated_by}"),
                ("Window", f"{format_ts(scope.since)} → {format_ts(scope.until)}"),
                ("Focus", scope.focus_label),
                ("Pot", _pot_line(scope.pot_name, scope.pot_id)),
                ("Source", scope.src_ip or "Any"),
                ("Raw logs", "Included" if scope.include_raw else "Omitted"),
            ]
        ),
        "</header>",
        "<h2>1. Executive summary</h2>",
        "".join(f"<p>{_esc(paragraph)}</p>" for paragraph in report.paragraphs),
        "<h2>2. Analyst notes</h2>",
        f'<div class="notes">{_esc(scope.analyst_notes)}</div>'
        if scope.analyst_notes
        else '<p class="muted">No analyst notes were added to this export.</p>',
        "<h2>3. Scope</h2>",
        _scope_html(report),
        "<h2>4. Indicators</h2>",
        _indicators_html(report),
        "<h2>5. Attacker profiles</h2>",
        _attackers_html(report),
        "<h2>6. Activity timeline</h2>",
        _timeline_html(report),
        "<h2>7. Commands and requests</h2>",
        _commands_html(report.commands),
        "<h2>8. Vulnerability correlation</h2>",
        _cves_html(report),
        "<h2>9. Evidence</h2>",
        _evidence_html(report.timeline),
        "<h2>10. Appendix</h2>",
        _appendix_html(report),
        f'<p class="footer">Generated by watchPot on {_esc(format_ts(scope.generated_at))}.</p>',
    ]
    return (
        "<!DOCTYPE html>\n"
        '<html lang="en">\n<head>\n'
        '<meta charset="utf-8">\n'
        '<meta name="viewport" content="width=device-width, initial-scale=1">\n'
        f"<title>{_esc(scope.title)}</title>\n"
        f"<style>{_CSS}</style>\n"
        "</head>\n<body>\n<article class=\"sheet\">\n"
        + "\n".join(body)
        + "\n</article>\n</body>\n</html>\n"
    )


def _esc(value: object) -> str:
    if value is None:
        return ""
    return html.escape(str(value), quote=True)


def _pot_line(name: str | None, pot_id: str | None) -> str:
    if name and pot_id:
        return f"{name} ({pot_id})"
    return name or pot_id or "All pots"


def _meta_table(rows: list[tuple[str, str]]) -> str:
    body = "".join(f"<tr><td>{_esc(label)}</td><td>{_esc(value)}</td></tr>" for label, value in rows)
    return f'<table class="meta"><tbody>{body}</tbody></table>'


def _table(headers: list[str], rows: list[list[str]]) -> str:
    head = "".join(f"<th>{_esc(header)}</th>" for header in headers)
    body = []
    for row in rows:
        cells = "".join(f"<td>{cell}</td>" for cell in row)
        body.append(f"<tr>{cells}</tr>")
    return f"<table><thead><tr>{head}</tr></thead><tbody>{''.join(body)}</tbody></table>"


def _plain_cell(value: object) -> str:
    return _esc(value if value not in (None, "") else "—")


def _scope_html(report: IncidentReport) -> str:
    if not report.pots:
        return '<p class="muted">No pots were in scope.</p>'
    rows = [
        [
            _plain_cell(pot.name),
            _plain_cell(pot.event_count),
            _plain_cell(pot.command_count),
            _plain_cell(pot.last_ip),
            f"<code>{_esc(pot.id)}</code>",
        ]
        for pot in report.pots
    ]
    html_parts = [_table(["Pot", "Events", "Commands", "Last agent IP", "Id"], rows)]
    for pot in report.pots:
        if pot.description:
            html_parts.append(f"<p><strong>{_esc(pot.name)}.</strong> {_esc(pot.description)}</p>")
    if report.services:
        names = ", ".join(f"<code>{_esc(name)}</code>" for name in report.services)
        html_parts.append(f"<p>Services and containers: {names}.</p>")
    return "".join(html_parts)


def _list_block(title: str, values: list[str], code: bool = False) -> str:
    if not values:
        items = '<p class="muted">None recorded.</p>'
    elif code:
        items = "<ul>" + "".join(f"<li><code>{_esc(value)}</code></li>" for value in values) + "</ul>"
    else:
        items = "<ul>" + "".join(f"<li>{_esc(value)}</li>" for value in values) + "</ul>"
    return f"<h3>{_esc(title)}</h3>{items}"


def _indicators_html(report: IncidentReport) -> str:
    parts = [
        _list_block("Source addresses", [attacker.ip_address for attacker in report.attackers], code=True),
        _list_block("Usernames", report.usernames, code=True),
        _list_block("Tools", [item.label for item in report.by_tool]),
        _list_block("Attack types", [f"{item.label} ({item.count})" for item in report.by_attack_type]),
        _list_block("Techniques", [item.label for item in report.by_technique], code=True),
        _list_block("Vulnerabilities", [item.cve_id for item in report.cves], code=True),
    ]
    if report.by_severity:
        mix = ", ".join(f"{_esc(item.label)} {item.count}" for item in report.by_severity)
        parts.append(f"<p>Severity mix: {mix}.</p>")
    return "".join(parts)


def _attackers_html(report: IncidentReport) -> str:
    if not report.attackers:
        return '<p class="muted">No source addresses were recorded for this scope.</p>'
    blocks: list[str] = []
    for attacker in report.attackers:
        geo = attacker.geo
        place = describe_place(geo.city, geo.region, geo.country) if geo else None
        network = (geo.asn_label or geo.org or geo.isp) if geo else None
        rows = [
            ["Status", attacker.status + ("" if attacker.tracked else " (not in the IP tracker)")],
            ["Location", place or "—"],
            ["Network", network or "—"],
            ["ISP", geo.isp if geo and geo.isp else "—"],
            ["Abuse score", str(attacker.abuse_score) if attacker.abuse_score is not None else "—"],
            ["Tor exit", yes_no(attacker.is_tor)],
            ["Hosting", yes_no(attacker.is_hosting)],
            ["Proxy", yes_no(geo.is_proxy) if geo else "—"],
            ["Tracker hits", str(attacker.hit_count) if attacker.hit_count is not None else "—"],
            ["Commands in this report", str(attacker.command_count)],
            ["Events in this report", str(attacker.event_count)],
            ["First seen", format_ts(attacker.first_seen_at)],
            ["Last seen", format_ts(attacker.last_seen_at)],
            ["Usernames", ", ".join(attacker.usernames) or "—"],
            ["Attack types", ", ".join(label_attack(item) for item in attacker.attack_types) or "—"],
            ["Tools", ", ".join(attacker.tools) or "—"],
            ["CVEs", ", ".join(attacker.cve_ids) or "—"],
            ["Tags", ", ".join(attacker.tags) or "—"],
        ]
        table = _table(["Field", "Value"], [[_plain_cell(left), _plain_cell(right)] for left, right in rows])
        notes = ""
        if attacker.user_notes:
            notes = f"<p>Operator notes</p><div class=\"quote\">{_esc(attacker.user_notes)}</div>"
        blocks.append(f'<section class="profile"><h3>{_esc(attacker.ip_address)}</h3>{table}{notes}</section>')
    return "".join(blocks)


def _timeline_html(report: IncidentReport) -> str:
    if not report.timeline:
        return '<p class="muted">No events were included.</p>'
    rows = []
    for event in report.timeline:
        attribution = []
        if event.source_ips:
            attribution.append(", ".join(event.source_ips))
        if event.attack_types:
            attribution.append(", ".join(label_attack(item) for item in event.attack_types))
        if event.tools:
            attribution.append(", ".join(event.tools))
        if event.cve_ids:
            attribution.append(", ".join(event.cve_ids))
        rows.append(
            [
                _plain_cell(format_ts(event.received_at)),
                _plain_cell(event.pot_name or event.pot_id),
                _plain_cell(event.service_name),
                f'<span class="sev-{_esc(event.severity.lower())}">{_esc(event.severity)}</span>',
                _plain_cell(event.summary or event.event_title),
                _plain_cell(" · ".join(attribution) or None),
            ]
        )
    return (
        _table(["Time (UTC)", "Pot", "Service", "Severity", "What happened", "Attribution"], rows)
        + "<p>Full payloads and log excerpts are in the evidence section.</p>"
    )


def _commands_html(commands: list[ReportCommand]) -> str:
    if not commands:
        return '<p class="muted">No shell commands, HTTP requests, logins, or downloads were captured in this scope.</p>'
    by_kind: dict[str, list[ReportCommand]] = {}
    for command in commands:
        by_kind.setdefault(command.kind, []).append(command)
    kinds = [kind for kind in KIND_ORDER if kind in by_kind]
    kinds.extend(kind for kind in by_kind if kind not in KIND_ORDER)
    parts: list[str] = []
    number = 1
    for kind in kinds:
        parts.append(f"<h3>{_esc(label_kind(kind))}</h3>")
        groups: dict[tuple[str, ...], list[ReportCommand]] = {}
        order: list[tuple[str, ...]] = []
        for command in by_kind[kind]:
            key = (
                command.session_id or "",
                command.src_ip or "",
                command.username or "",
                command.pot_id,
                command.container or "",
            )
            if key not in groups:
                order.append(key)
                groups[key] = []
            groups[key].append(command)
        for key in order:
            sample = groups[key][0]
            bits = [f"Session {sample.session_id}" if sample.session_id else "No session id"]
            if sample.src_ip:
                bits.append(sample.src_ip)
            if sample.username:
                bits.append(f"user {sample.username}")
            if sample.pot_name:
                bits.append(sample.pot_name)
            if sample.container:
                bits.append(f"container {sample.container}")
            parts.append(f"<h4>{_esc(' · '.join(bits))}</h4>")
            for command in groups[key]:
                repeats = ""
                if command.hit_count > 1:
                    repeats = (
                        f" Observed {command.hit_count} times"
                        f" ({format_ts(command.first_seen_at)} → {format_ts(command.last_seen_at)})."
                    )
                event_bit = f" Event {command.event_id}." if command.event_id else ""
                parts.append(
                    f"<p><strong>{number}.</strong> {_esc(format_ts(command.observed_at))}.{_esc(repeats)}{_esc(event_bit)}</p>"
                )
                parts.append(f"<pre>{_esc(command.command)}</pre>")
                if command.context:
                    parts.append("<p>Surrounding log</p>")
                    parts.append(f"<pre>{_esc(command.context)}</pre>")
                number += 1
    return "".join(parts)


def _cves_html(report: IncidentReport) -> str:
    if not report.cves:
        return '<p class="muted">No CVEs were correlated with this activity.</p>'
    blocks: list[str] = []
    for cve in report.cves:
        score = f"{cve.cvss_score:g}" if cve.cvss_score is not None else "—"
        product = " ".join(part for part in (cve.vendor, cve.product) if part) or "—"
        rows = [
            ["Severity", cve.severity or "—"],
            ["CVSS", score],
            ["Category", cve.category or "—"],
            ["Product", product],
            ["In local cache", "Yes" if cve.in_cache else "No — id only, or taken from the event"],
            ["Events", str(cve.event_count)],
            ["Source addresses", ", ".join(cve.source_ips) or "—"],
        ]
        table = _table(["Field", "Value"], [[_plain_cell(a), _plain_cell(b)] for a, b in rows])
        summary = f"<p>{_esc(cve.summary)}</p>" if cve.summary else ""
        notes = f'<div class="quote">{_esc(cve.notes)}</div>' if cve.notes else ""
        refs = ""
        if cve.references:
            items = []
            for ref in cve.references:
                if ref.startswith("https://") or ref.startswith("http://"):
                    href = _esc(ref)
                    items.append(f'<li><a href="{href}">{href}</a></li>')
                else:
                    items.append(f"<li>{_esc(ref)}</li>")
            refs = "<ul>" + "".join(items) + "</ul>"
        blocks.append(f"<section><h3>{_esc(cve.cve_id)}</h3>{table}{summary}{notes}{refs}</section>")
    return "".join(blocks)


def _evidence_html(events: list[ReportEvent]) -> str:
    if not events:
        return '<p class="muted">No event evidence was included.</p>'
    blocks: list[str] = []
    for index, event in enumerate(events, start=1):
        rows = [
            ["Event id", event.id],
            ["Time", format_ts(event.received_at)],
            ["Pot", _pot_line(event.pot_name, event.pot_id)],
            ["Stack", event.stack_name or event.stack_id or "—"],
            ["Service", event.service_name or "—"],
            ["Type", event.event_type],
            ["Channel", event.channel],
            ["Source", event.source],
            ["Severity", event.severity],
            ["Summary", event.summary or "—"],
            ["Source addresses", ", ".join(event.source_ips) or "—"],
            ["Enrichment", event.enrichment_status or "—"],
            ["Confidence", _confidence(event.confidence)],
            ["Attack types", ", ".join(label_attack(item) for item in event.attack_types) or "—"],
            ["Tools", ", ".join(event.tools) or "—"],
            ["Techniques", ", ".join(event.techniques) or "—"],
            ["Rules", ", ".join(event.rule_names) or "—"],
            ["CVEs", ", ".join(event.cve_ids) or "—"],
        ]
        table = _table(["Field", "Value"], [[_plain_cell(a), _plain_cell(b)] for a, b in rows])
        details = []
        for detail in event.cve_details:
            score = f", CVSS {detail.cvss_score:g}" if detail.cvss_score is not None else ""
            summary = detail.summary or "No summary stored."
            details.append(
                f"<li><strong>{_esc(detail.cve_id)}</strong> ({_esc(detail.severity or 'unknown')}{_esc(score)}): {_esc(summary)}</li>"
            )
        detail_html = f"<ul>{''.join(details)}</ul>" if details else ""
        payload = ""
        if event.payload:
            note = " Payload was shortened." if event.payload_truncated else ""
            encoded = json.dumps(event.payload, indent=2, ensure_ascii=False, default=str)
            payload = f"<p>Payload.{_esc(note)}</p><pre>{_esc(encoded)}</pre>"
        if event.raw_log:
            note = " Log was shortened." if event.raw_log_truncated else ""
            raw = f"<p>Raw log.{_esc(note)}</p><pre>{_esc(event.raw_log)}</pre>"
        else:
            raw = '<p class="muted">Raw log was not included.</p>'
        blocks.append(
            f'<section class="event"><h3>{index}. {_esc(event.event_title)}</h3>{table}{detail_html}{payload}{raw}</section>'
        )
    return "".join(blocks)


def _appendix_html(report: IncidentReport) -> str:
    if report.scope.truncation_notes:
        limits = "<ul>" + "".join(f"<li>{_esc(note)}</li>" for note in report.scope.truncation_notes) + "</ul>"
    else:
        limits = "<p>This export was not truncated.</p>"
    events = (
        "<ul>" + "".join(f"<li><code>{_esc(event.id)}</code></li>" for event in report.timeline) + "</ul>"
        if report.timeline
        else '<p class="muted">None.</p>'
    )
    commands = (
        "<ul>" + "".join(f"<li><code>{_esc(command.id)}</code></li>" for command in report.commands) + "</ul>"
        if report.commands
        else '<p class="muted">None.</p>'
    )
    return (
        f"{limits}<h3>Event ids ({len(report.timeline)})</h3>{events}"
        f"<h3>Command ids ({len(report.commands)})</h3>{commands}"
    )


def _confidence(value: float | None) -> str:
    if value is None:
        return "—"
    return f"{round(value * 100)}%"
